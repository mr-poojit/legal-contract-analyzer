export function createDocPages(text: string): DocumentPage[] {
  const parts = text.split(/\n\s*\n\s*\n/);
  const pages: DocumentPage[] = [];
  let currentOffset = 0;

  for (let i = 0; i < parts.length; i++) {
    const part = parts[i].trim();
    if (!part) continue;
    const start = text.indexOf(part, currentOffset);
    const startOffset = start !== -1 ? start : currentOffset;
    const endOffset = startOffset + part.length;
    currentOffset = endOffset;

    pages.push({
      pageNumber: pages.length + 1,
      text: part,
      startOffset,
      endOffset,
    });
  }

  if (pages.length === 0) {
    pages.push({
      pageNumber: 1,
      text,
      startOffset: 0,
      endOffset: text.length,
    });
  }

  return pages;
}

export interface SampleDocRecord {
  id: string;
  name: string;
  originalName: string;
  fileType: 'pdf' | 'docx';
  text: string;
  pages: DocumentPage[];
  meta: DocumentMeta;
}

function buildSampleDoc(
  id: string,
  name: string,
  originalName: string,
  fileType: 'pdf' | 'docx',
  text: string
): SampleDocRecord {
  const pages = createDocPages(text);
  const wordCount = text.trim().split(/\s+/).filter(Boolean).length;
  const meta: DocumentMeta = {
    id,
    name,
    originalName,
    fileType,
    fileSize: text.length * 2,
    uploadedAt: '2024-03-01T00:00:00.000Z',
    status: 'ready',
    pageCount: pages.length,
    wordCount,
    textLength: text.length,
  };
  return { id, name, originalName, fileType, text, pages, meta };
}

